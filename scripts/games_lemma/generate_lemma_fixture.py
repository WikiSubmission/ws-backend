#!/usr/bin/env python3
"""Generate the game_lemma seed fixture for Quran Games (Hard-tier acceptance).

Reads a vocabulary on stdin (one normalized word per line, lowercase, letters
and digits only -- exactly as stored in game_word_frequency.word_normalized),
lemmatizes each word with spaCy, and writes a SQL fixture to stdout.

Only words whose lemma differs from the word itself are emitted. Identity
mappings are pointless: the Go matcher already falls back to exact match when a
word is absent from game_lemma. Dropping them keeps the fixture small.

This is a one-time / regenerate-on-demand job. The committed SQL fixture is
what production loads; spaCy is never needed at deploy or request time.

Usage:
    psql "$DB_URL" -tAc \\
      "SELECT DISTINCT word_normalized FROM game_word_frequency WHERE language='en'" \\
      | python3 generate_lemma_fixture.py --language en \\
      > ../../assets/source_data/games_lemma_en.sql

Requires:
    pip install -r requirements.txt
    python -m spacy download en_core_web_sm
"""

import argparse
import sys

BATCH_SIZE = 1000


def load_nlp():
    try:
        import spacy
    except ImportError:
        sys.exit(
            "spaCy is not installed. Run:\n"
            "  pip install -r requirements.txt\n"
            "  python -m spacy download en_core_web_sm"
        )
    try:
        # Disable everything except the lemmatizer's prerequisites for speed.
        return spacy.load("en_core_web_sm", disable=["ner", "parser"])
    except OSError:
        sys.exit(
            "spaCy model 'en_core_web_sm' is not installed. Run:\n"
            "  python -m spacy download en_core_web_sm"
        )


def sql_escape(s: str) -> str:
    return s.replace("'", "''")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--language", default="en", help="language code for the rows (default: en)")
    args = parser.parse_args()

    if args.language != "en":
        sys.exit(f"unsupported language {args.language!r} (v1 only ships 'en')")

    words = []
    seen = set()
    for line in sys.stdin:
        w = line.strip().lower()
        if not w or w in seen:
            continue
        seen.add(w)
        words.append(w)

    if not words:
        sys.exit("no vocabulary received on stdin")

    nlp = load_nlp()

    # Map each word to its lemma. Process as single-token docs; the small model
    # lemmatizes a bare word fine for our acceptance use-case.
    mappings = []  # (word, lemma)
    for doc in nlp.pipe(words, batch_size=256):
        if len(doc) == 0:
            continue
        word = doc.text
        lemma = doc[0].lemma_.strip().lower()
        if not lemma or lemma == word:
            continue
        # Keep lemmas to the same normalized alphabet as the keys.
        if not lemma.isalnum():
            lemma = "".join(ch for ch in lemma if ch.isalnum())
            if not lemma or lemma == word:
                continue
        mappings.append((word, lemma))

    write_sql(args.language, mappings)
    print(
        f"-- generated {len(mappings)} lemma rows from {len(words)} words",
        file=sys.stderr,
    )


def write_sql(language: str, mappings) -> None:
    out = sys.stdout
    out.write("-- Quran Games lemma fixture. GENERATED by scripts/games_lemma/generate_lemma_fixture.py.\n")
    out.write("-- Do not edit by hand. Regenerate with: just games-build-lemma-fixture <target>\n")
    out.write("BEGIN;\n")
    out.write(f"DELETE FROM game_lemma WHERE language = '{sql_escape(language)}';\n")

    if not mappings:
        out.write("COMMIT;\n")
        return

    for i in range(0, len(mappings), BATCH_SIZE):
        batch = mappings[i : i + BATCH_SIZE]
        out.write("INSERT INTO game_lemma (language, word_normalized, lemma) VALUES\n")
        rows = [
            f"  ('{sql_escape(language)}', '{sql_escape(w)}', '{sql_escape(lemma)}')"
            for (w, lemma) in batch
        ]
        out.write(",\n".join(rows))
        out.write("\nON CONFLICT (language, word_normalized) DO UPDATE SET lemma = EXCLUDED.lemma;\n")

    out.write("COMMIT;\n")


if __name__ == "__main__":
    main()
